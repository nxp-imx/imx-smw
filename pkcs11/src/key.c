/**
 * C_GenerateKey() - Generates a symmetric key.
 * @hSession: [in] The session's handle.
 * @pMechanism: [in] Pointer to the key generation mechanism.
 * @pTemplate: [in] Pointer to the template of the key attributes to create.
 * @ulCount: [in] Number of attributes in the template.
 * @phKey: [out] Pointer to the location that receives the handle of the new key.
 *
 * This function generates a symmetric key, creating a new key object.
 *
 * The type of key generated depends on the mechanism specified, hence
 * it is not necessary to specify key type in template. If specified, it must
 * match the key type generated by the mechanism otherwise function returns
 * CKR_TEMPLATE_INCONSISTENT error.
 *
 * The class CKA_CLASS attribute is not needed as well, if specified and not
 * CKO_SECRET_KEY, the function returns CKR_TEMPLATE_INCONSISTENT error.
 *
 * Return:
 *  - CKR_OK:
 *      Success.
 *  - CKR_ARGUMENTS_BAD:
 *      The @phKey is NULL.
 *  - CKR_SESSION_HANDLE_INVALID:
 *      The session handle is not valid.
 *  - CKR_MECHANISM_PARAM_INVALID:
 *      The @pMechanism is NULL.
 *  - CKR_TEMPLATE_INCOMPLETE:
 *      The @pTemplate and @ulCount is incomplete or inconsistent.
 *  - CKR_TEMPLATE_INCONSISTENT:
 *      One of the template's attribute type must not be defined.
 *  - CKR_ATTRIBUTE_READ_ONLY:
 *      One attribute is read only
 *  - CKR_ATTRIBUTE_VALUE_INVALID:
 *      One of the template's attribute value is not valid.
 *  - CKR_USER_NOT_LOGGED_IN:
 *      User must login to create object.
 *  - CKR_SLOT_ID_INVALID:
 *      Slot ID is not valid.
 *  - CKR_MECHANISM_INVALID:
 *      Mechanism not supported.
 *  - CKR_HOST_MEMORY:
 *      Allocation error.
 *  - CKR_SESSION_CLOSED:
 *      Session closed.
 *  - CKR_FUNCTION_FAILED:
 *      Function failure.
 *  - CKR_FUNCTION_CANCELED:
 *      Application callback canceled function.
 *  - CKR_TOKEN_NOT_PRESENT:
 *      Token not present.
 *  - CKR_GENERAL_ERROR:
 *      General error.
 *  - CKR_CRYPTOKI_NOT_INITIALIZED:
 *      The library has not been previously initialized by :c:func:`C_Initialize`.
 *  - Other errors from the underlying implementation.
 */
CK_RV C_GenerateKey(CK_SESSION_HANDLE hSession, CK_MECHANISM_PTR pMechanism,
		    CK_ATTRIBUTE_PTR pTemplate, CK_ULONG ulCount,
		    CK_OBJECT_HANDLE_PTR phKey)
{
	if (!hSession)
		return CKR_SESSION_HANDLE_INVALID;

	if (!pMechanism)
		return CKR_MECHANISM_PARAM_INVALID;

	/*
	 * Key template attributes may not be necessary
	 */
	if ((!pTemplate && ulCount) || (pTemplate && !ulCount))
		return CKR_TEMPLATE_INCOMPLETE;

	if (!phKey)
		return CKR_ARGUMENTS_BAD;

	return libobj_generate_key(hSession, pMechanism, pTemplate, ulCount,
				   phKey);
}

/**
 * C_GenerateKeyPair() - Generates an asymmetric key pair.
 * @hSession: [in] The session's handle.
 * @pMechanism: [in] Pointer to the key generation mechanism.
 * @pPublicKeyTemplate: [in] Pointer to the template of the public key
 *                           attributes to create.
 * @ulPublicKeyAttributeCount: [in] Number of attributes in the public key
 *                                  template.
 * @pPrivateKeyTemplate: [in] Pointer to the template of the private key
 *                            attributes to create.
 * @ulPrivateKeyAttributeCount: [in] Number of attributes in the private key
 *                                   template.
 * @phPublicKey: [out] Pointer to the location that receives the handle of the
 *                     public key.
 * @phPrivateKey: [out] Pointer to the location that receives the handle of the
 *                      private key.
 *
 * This function generates an asymmetric key pair, creating new key objects.
 *
 * The type of key generated depends on the mechanism specified, hence
 * it is not necessary to specify key type in templates. If specified, it must
 * match the key type generated by the mechanism otherwise function returns
 * CKR_TEMPLATE_INCONSISTENT error.
 *
 * The class CKA_CLASS attribute is not needed as well, if specified and not
 * CKO_PUBLIC_KEY or CKO_PRIVATE_KEY in the respective Public and Private
 * template, the function returns CKR_TEMPLATE_INCONSISTENT error.
 *
 * Return:
 *  - CKR_OK:
 *      Success.
 *  - CKR_ARGUMENTS_BAD:
 *      - The @phPublic is NULL.
 *      - The @phPrivateKey is NULL.
 *  - CKR_SESSION_HANDLE_INVALID:
 *      The session handle is not valid.
 *  - CKR_MECHANISM_PARAM_INVALID:
 *      The @pMechanism is NULL.
 *  - CKR_TEMPLATE_INCOMPLETE:
 *      The @pTemplate and @ulCount is incomplete or inconsistent.
 *  - CKR_TEMPLATE_INCONSISTENT:
 *      One of the template's attribute type must not be defined.
 *  - CKR_ATTRIBUTE_READ_ONLY:
 *      One attribute is read only
 *  - CKR_ATTRIBUTE_VALUE_INVALID:
 *      One of the template's attribute value is not valid.
 *  - CKR_USER_NOT_LOGGED_IN:
 *      User must login to create object.
 *  - CKR_SLOT_ID_INVALID:
 *      Slot ID is not valid.
 *  - CKR_MECHANISM_INVALID:
 *      Mechanism not supported.
 *  - CKR_HOST_MEMORY:
 *      Allocation error.
 *  - CKR_SESSION_CLOSED:
 *      Session closed.
 *  - CKR_FUNCTION_FAILED:
 *      Function failure.
 *  - CKR_FUNCTION_CANCELED:
 *      Application callback canceled function.
 *  - CKR_TOKEN_NOT_PRESENT:
 *      Token not present.
 *  - CKR_GENERAL_ERROR:
 *      General error.
 *  - CKR_CRYPTOKI_NOT_INITIALIZED:
 *      The library has not been previously initialized by :c:func:`C_Initialize`.
 *  - Other errors from the underlying implementation.
 */
CK_RV C_GenerateKeyPair(CK_SESSION_HANDLE hSession, CK_MECHANISM_PTR pMechanism,
			CK_ATTRIBUTE_PTR pPublicKeyTemplate,
			CK_ULONG ulPublicKeyAttributeCount,
			CK_ATTRIBUTE_PTR pPrivateKeyTemplate,
			CK_ULONG ulPrivateKeyAttributeCount,
			CK_OBJECT_HANDLE_PTR phPublicKey,
			CK_OBJECT_HANDLE_PTR phPrivateKey)
{
	if (!hSession)
		return CKR_SESSION_HANDLE_INVALID;

	if (!pMechanism)
		return CKR_MECHANISM_PARAM_INVALID;

	if (!pPublicKeyTemplate || !ulPublicKeyAttributeCount)
		return CKR_TEMPLATE_INCOMPLETE;

	/*
	 * Private key template attributes may not be necessary
	 */
	if ((!pPrivateKeyTemplate && ulPrivateKeyAttributeCount) ||
	    (pPrivateKeyTemplate && !ulPrivateKeyAttributeCount))
		return CKR_TEMPLATE_INCOMPLETE;

	if (!phPublicKey || !phPrivateKey)
		return CKR_ARGUMENTS_BAD;

	return libobj_generate_keypair(hSession, pMechanism, pPublicKeyTemplate,
				       ulPublicKeyAttributeCount,
				       pPrivateKeyTemplate,
				       ulPrivateKeyAttributeCount, phPublicKey,
				       phPrivateKey);
}

