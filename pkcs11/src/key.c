/**
 * C_DeriveKey() - Derives a secret key from a base key.
 * @hSession: [in] The session's handle.
 * @pMechanism: [in] Pointer to the key derivation mechanism.
 * @hBaseKey: [in] Handle of the base key.
 * @pTemplate: [in] Pointer to the template attributes for the new key.
 * @ulAttributeCount: [in] Number of attributes in the template.
 * @phKey: [out] Pointer to the location that receives the handle of the derived
 *               key.
 *
 * This function derives a secret key from a base key, creating a new key
 * object.
 *
 * The class CKA_CLASS attribute is not needed as well, if specified and not
 * CKO_PUBLIC_KEY or CKO_PRIVATE_KEY in the respective Public and Private
 * template, the function returns CKR_TEMPLATE_INCONSISTENT error.
 *
 * If the derived key type is a supported key derivation type, the function
 * returns CKR_TEMPLATE_INCONSISTENT errro.
 *
 * Return:
 *  - CKR_OK:
 *      Success.
 *  - CKR_SESSION_HANDLE_INVALID:
 *      The session handle is not valid.
 *  - CKR_KEY_HANDLE_INVALID:
 *      The @hBaseKey is not valid.
 *  - CKR_ARGUMENTS_BAD:
 *      - The @pMechanism is NULL.
 *      - If the mechanism is not CKM_TLS12_KEY_AND_MAC_DERIVE and @phKey is
 *        NULL.
 *  - CKR_TEMPLATE_INCOMPLETE:
 *      The @pTemplate and @ulCount is incomplete or inconsistent.
 *  - CKR_TEMPLATE_INCONSISTENT:
 *      One of the template's attribute type must not be defined.
 *  - CKR_ATTRIBUTE_READ_ONLY:
 *      One attribute is read only
 *  - CKR_ATTRIBUTE_VALUE_INVALID:
 *      One of the template's attribute value is not valid.
 *  - CKR_USER_NOT_LOGGED_IN:
 *      User must login to create object.
 *  - CKR_SLOT_ID_INVALID:
 *      Slot ID is not valid.
 *  - CKR_MECHANISM_INVALID:
 *      Mechanism not supported.
 *  - CKR_HOST_MEMORY:
 *      Allocation error.
 *  - CKR_SESSION_CLOSED:
 *      Session closed.
 *  - CKR_FUNCTION_FAILED:
 *      Function failure.
 *  - CKR_FUNCTION_CANCELED:
 *      Application callback canceled function.
 *  - CKR_TOKEN_NOT_PRESENT:
 *      Token not present.
 *  - CKR_GENERAL_ERROR:
 *      General error.
 *  - CKR_CRYPTOKI_NOT_INITIALIZED:
 *      The library has not been previously initialized by :c:func:`C_Initialize`.
 *  - Other errors from the underlying implementation.
 */
CK_RV C_DeriveKey(CK_SESSION_HANDLE hSession, CK_MECHANISM_PTR pMechanism,
		  CK_OBJECT_HANDLE hBaseKey, CK_ATTRIBUTE_PTR pTemplate,
		  CK_ULONG ulAttributeCount, CK_OBJECT_HANDLE_PTR phKey)
{
	if (!hSession)
		return CKR_SESSION_HANDLE_INVALID;

	if (!pMechanism)
		return CKR_ARGUMENTS_BAD;

	if (!hBaseKey)
		return CKR_KEY_HANDLE_INVALID;

	if (!pTemplate != !ulAttributeCount)
		return CKR_TEMPLATE_INCOMPLETE;

	return libobj_derive_key(hSession, pMechanism, hBaseKey, pTemplate,
				 ulAttributeCount, phKey);
}

