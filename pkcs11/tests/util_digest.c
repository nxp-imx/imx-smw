bool check_digest_length(unsigned long exp_digest_length,
			 unsigned long digest_length)
{
	if (digest_length != exp_digest_length) {
		TEST_OUT("Digest length is wrong: %ld (expected %ld)\n",
			 digest_length, exp_digest_length);

		return false;
	}

	return true;
}

bool check_digest(const unsigned char *exp_digest,
		  unsigned long exp_digest_length, const unsigned char *digest,
		  unsigned long digest_length)
{
	if (!check_digest_length(exp_digest_length, digest_length))
		return false;

	if (digest && memcmp(digest, exp_digest, exp_digest_length)) {
		TEST_OUT("Digest buffer mismatch\n");

		return false;
	}

	return true;
}
